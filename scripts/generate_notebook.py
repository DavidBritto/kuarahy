    "def calculate_parcel_economics(area_ha=20.0, dni_kwh_m2_day=5.4, topology=\"Single-Axis Trackers\"):\n",
    "    \"\"\"\n",
    "    Calculates project financials: installed capacity, turnkey CapEx, annual revenue, and payback.\n",
    "    \"\"\"\n",
    "    capacity_mw = round(area_ha * 0.65, 2)\n",
    "    annual_generation_mwh = round(capacity_mw * 1000 * dni_kwh_m2_day * 365 * 0.78 / 1000, 1)\n",
    "    \n",
    "    turnkey_capex_usd = round(capacity_mw * 820_000)\n",
    "    annual_gross_revenue_usd = round(annual_generation_mwh * 65.0) # $65 USD/MWh PPA\n",
    "    annual_om_usd = round(capacity_mw * 12_000)\n",
    "    annual_net_cashflow_usd = annual_gross_revenue_usd - annual_om_usd\n",
    "    \n",
    "    simple_payback_years = round(turnkey_capex_usd / annual_net_cashflow_usd, 1)\n",
    "    ten_year_net_return_usd = round((annual_net_cashflow_usd * 10) - turnkey_capex_usd)\n",
    "    co2_offset_tons_per_year = round(annual_generation_mwh * 0.42)\n",
    "    \n",
    "    return {\n",
    "        \"area_ha\": area_ha,\n",
    "        \"topology\": topology,\n",
    "        \"capacity_mw\": capacity_mw,\n",
    "        \"annual_generation_mwh\": annual_generation_mwh,\n",
    "        \"turnkey_capex_usd\": turnkey_capex_usd,\n",
    "        \"annual_gross_revenue_usd\": annual_gross_revenue_usd,\n",
    "        \"payback_years\": simple_payback_years,\n",
    "        \"ten_year_net_return_usd\": ten_year_net_return_usd,\n",
    "        \"co2_offset_tons_year\": co2_offset_tons_per_year\n",
    "    }\n",
