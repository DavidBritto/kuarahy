    "    elevation = telemetry_point['elevation']\n",
    "    \n",
    "    # Evaluated Priority Decision Tree\n",
    "    if wind > 60.0:\n",
    "        chosen = \"emergency_storm_stow\"\n",
    "        motor_tilt = 0.0\n",
    "        status = \"Gale Wind Defense Stow\"\n",
    "    elif rain > 1.5 and soiling > 4.0:\n",
    "        chosen = \"clean_panels_rainwash\"\n",
    "        motor_tilt = 65.0\n",
    "        status = \"Autonomous Rainwash Hydro-Cleaning\"\n",
    "    elif battery_soc < 15.0:\n",
    "        chosen = \"battery_conservation_hold\"\n",
    "        motor_tilt = 0.0\n",
    "        status = \"Battery Low Conservation\"\n",
    "    elif elevation > 0.0:\n",
    "        chosen = \"follow_sun_optimal_tracking\"\n",
    "        hour_val = float(telemetry_point['hour'][:2])\n",
