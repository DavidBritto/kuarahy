    "def synthesize_with_bedrock(metrics, region=\"us-west-2\"):\n",
    "    \"\"\"\n",
    "    Invokes Amazon Bedrock Converse API with Amazon Nova Lite.\n",
    "    Falls back transparently if offline or credentials are being verified.\n",
    "    \"\"\"\n",
    "    prompt = f\"\"\"You are the lead solar energy economist for Solaria.\n",
    "A commercial solar field parcel of {metrics['area_ha']} hectares has been evaluated:\n",
    "- Technology: {metrics['topology']}\n",
    "- Installed Capacity: {metrics['capacity_mw']} MWp\n",
    "- Estimated Annual Generation: {metrics['annual_generation_mwh']:,} MWh/year\n",
    "- Turnkey CapEx: ${metrics['turnkey_capex_usd']:,} USD\n",
    "- Simple Payback Period: {metrics['payback_years']} years\n",
    "- 10-Year Cumulative Net Return: ${metrics['ten_year_net_return_usd']:,} USD\n",
    "- Annual CO2 Emissions Offset: {metrics['co2_offset_tons_year']:,} tons CO2/year\n",
    "\n",
    "Provide:\n",
    "1. An executive 2-paragraph investment thesis for energy funds or landowners.\n",
    "2. 3 bulleted key financial highlights.\n",
    "3. A concise note on Frugal Architecture: why sub-115ms edge decisions (AWS Strands Decider 2B) were combined with on-demand Bedrock generative synthesis.\n",
    "\"\"\"\n",
    "    start_time = time.perf_counter()\n",
    "    \n",
    "    try:\n",
    "        bedrock = boto3.client('bedrock-runtime', region_name=region)\n",
    "        response = bedrock.converse(\n",
    "            modelId='amazon.nova-lite-v1:0',\n",
    "            messages=[{'role': 'user', 'content': [{'text': prompt}]}],\n",
    "            inferenceConfig={'maxTokens': 600, 'temperature': 0.3}\n",
    "        )\n",
    "        elapsed_ms = round((time.perf_counter() - start_time) * 1000)\n",
    "        text = response['output']['message']['content'][0]['text']\n",
    "        \n",
    "        return {\n",
    "            \"engine\": \"amazon-bedrock\",\n",
    "            \"modelId\": \"amazon.nova-lite-v1:0\",\n",
    "            \"latency_ms\": elapsed_ms,\n",
    "            \"thesis\": text\n",
    "        }\n",
    "    except Exception as e:\n",
